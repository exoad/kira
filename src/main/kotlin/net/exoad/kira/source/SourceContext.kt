/**
 * a source context represents a single source file and contains all the processed information for that source file
 * this includes information like:
 *
 * 1. the raw preprocessed content (everything after [net.exoad.kira.compiler.frontend.preprocessor.KiraPreprocessor])
 * 2. the lexical tokens generated by [net.exoad.kira.compiler.frontend.lexer.KiraLexer]
 * 3. the [ast] generated by [net.exoad.kira.compiler.frontend.parser.KiraParser]
 */
class SourceContext(val content: String, val file: String, val tokens: List<Token>) {
    private val lines: List<String> = content.lines()

    /** The file's module URI (`project:path.to.file`), set by whoever reads the file; the file is the module. */
    var moduleName: String? = null
    lateinit var ast: RootASTNode
    lateinit var astOrigins: IdentityHashMap<ASTNode, SourcePosition>
    lateinit var astIntrinsicMarked: IdentityHashMap<ASTNode, Array<CompilerIntrinsic>>

    /**
     * The marker intrinsics of each marked declaration as the parser saw them,
     * arguments included: `@_extern("sym")` keeps its "sym" here, where
     * [astIntrinsicMarked] holds only the registry entries. Same keys as
     * [astIntrinsicMarked]; read it with [intrinsicInvocationsOf].
     */
    lateinit var astIntrinsicInvocations: IdentityHashMap<ASTNode, List<IntrinsicExpr>>

    /** The expressions written inside parentheses, which the AST does not keep. */
    val astParenthesized: MutableSet<ASTNode> = Collections.newSetFromMap(IdentityHashMap())

    /** Declarations written with the removed `= value` ([DeclEquals]), in source order; filled only when [lenientDeclEquals]. */
    val astDeclEquals: MutableList<DeclEquals> = mutableListOf()

    /** Set by the rewrite tool: the parser notes each removed `x: T = v` in [astDeclEquals] and goes on, where it refuses it. */
    var lenientDeclEquals: Boolean = false

    /** Loops written with the removed `for` ([ForLoopRecord]), in the order their bodies close; filled only when [lenientFor]. */
    val astFors: MutableList<ForLoopRecord> = mutableListOf()

    /** Set by the rewrite tool: the parser notes each removed `for` in [astFors] and reads its body as a `while`'s, where it refuses it. */
    var lenientFor: Boolean = false

    /** The marker invocations on [node], with their arguments; empty when it has none. */
    fun <T : ASTNode> intrinsicInvocationsOf(node: T): List<IntrinsicExpr> {
        if (!::astIntrinsicInvocations.isInitialized) {
            return emptyList()
        }
        return astIntrinsicInvocations[node] ?: emptyList()
    }

    /**
     * Returns the module declaration representing this source module
     *
     * It is required that this node exists in the ast tree
     */
    private lateinit var moduleUri: String

    fun getModuleUri(): String {
        if (!::ast.isInitialized) {
            Diagnostics.panic("Failed to acquire module_uri for '$file' because the AST was not loaded yet!")
        }
        if (!::moduleUri.isInitialized) {
            // ast.statements contains Statement nodes, each with an expr property
            for (node in ast.statements) {
                if (node is net.exoad.kira.compiler.frontend.parser.ast.statements.Statement) {
                    val expr = node.expr
                    if (expr is ModuleDecl) {
                        moduleUri = expr.uri.value
                        return moduleUri
                    }
                }
            }
            // fallback if no module declaration found
            moduleUri = "(unknown):(unknown)"
        }
        return moduleUri
    }

    fun with(content: String, tokens: List<Token>? = null): SourceContext {
        return SourceContext(content, file, tokens ?: this.tokens).also { it.moduleName = moduleName }
    }

    fun <T : ASTNode> isIntrinsified(node: T): Boolean {
        return astIntrinsicMarked[node]?.isNotEmpty() ?: false
    }

    fun <T : ASTNode> intrinsicsOf(node: T): Array<CompilerIntrinsic> {
        if (!isIntrinsified(node)) {
            Diagnostics.panic("Kira", "$node has no intrinsic markers.", context = this)
        }
        return astIntrinsicMarked[node]!!
    }

    fun <T : ASTNode> relativeOriginOf(node: T): SourcePosition {
        if (!astOrigins.containsKey(node)) {
            Diagnostics.panic("Kira", "Could not find a saved location for $node", context = this)
        }
        return astOrigins[node]!!
    }

    /**
     * 1-based indexing (is this lua? when anything refers to canonicity in my code, it often just means the way that ordinary folks (users of the language) would refer to things or like things
     */
    fun findCanonicalLine(lineNumber: Int): String {
        return lines[lineNumber - 1]
    }

    /**
     * Creates a visual pointer to a portion of [content] by the specified [sourcePosition] and how long of the content to point at [locatorLength]
     *
     * - [locatorLength] starts at the first character of [sourcePosition]'s [SourcePosition.column] parameter. *PS, this function will throw an assertion error if [locatorLength] is not `>=` (greater than or equal to) `1`*
     *
     * - commonly used by the [Diagnostics.panic] function to generate useful & friendly error messages
     */
    fun formCanonicalLocatorString(
        sourcePosition: SourcePosition,
        trailingText: String? = null,
        locatorLength: Int = 1,
    ): String {
        assert(locatorLength >= 1) { "Locator length must be visible!" }
        val line = findCanonicalLine(sourcePosition.lineNumber)
        return buildString {
            appendLine("@[${file}] : $sourcePosition")
            append(
                when {
                    sourcePosition.column < 0 || line.isNotRepresentableDiagnosticsSymbol() -> line
                    else -> {
                        val builder = StringBuilder()
                        val gutter = "${"X".repeat(sourcePosition.lineNumber.toString().length)}| "
                        builder.appendLine(gutter)
                        builder.appendLine("${sourcePosition.lineNumber}| $line")
                        // makes sure the arrows are always aligned properly to the actual selected portion of the line
                        val gap = " ".repeat(sourcePosition.column - 1)
                        builder.append(gutter)
                        builder.append(gap)
                        builder.appendLine(
                            "^".repeat(locatorLength)
                        )
                        if (trailingText != null) {
                            // allow for multi line and adjusts the gutter to allow for multi line support!
                            for (bit in trailingText.split("\n")) {
                                builder.append(gutter)
                                builder.append(gap)
                                builder.append(bit)
                                builder.appendLine()
                            }
                        }
                        builder.toString()
                    }
                }
            )
        }
    }
}

/** One text change on a line of the preprocessed content: the columns [startColumn] up to [endColumn] (1-based, exclusive) become [text]. */
class DeclEdit(val line: Int, val startColumn: Int, val endColumn: Int, val text: String) {
    /** [raw] (the line, or its raw twin: the columns before any comment agree) with the change made. */
    fun applyTo(raw: String): String = raw.substring(0, startColumn - 1) + text + raw.substring(minOf(endColumn - 1, raw.length))
}

/**
 * One declaration written with the removed `= value` (`x: T = v`, `NAME: T = T { .. }`): [decl] is it, [local] its name,
 * and [edits] (all on lines of the preprocessed content) rewrite it to braces (`x: T { v }`, `NAME: T { .. }`).
 */
class DeclEquals(val decl: ASTNode, val local: String, val firstLine: Int, val lastLine: Int, val edits: List<DeclEdit>) {
    /** The declaration's lines of [lines] with its edits applied, joined at the newline. */
    fun applied(lines: List<String>): String {
        val out = lines.toMutableList()
        for (e in edits.sortedWith(compareByDescending<DeclEdit> { it.line }.thenByDescending { it.startColumn })) out[e.line - 1] = e.applyTo(out[e.line - 1])
        return out.subList(firstLine - 1, lastLine).joinToString("\n")
    }
}

/**
 * One loop written with the removed `for`: [loop] stands in for it in the tree (its body is the loop's), [forAt] is the
 * `for` token, [openAt] and [closeAt] the body's braces, and [head] the text between `for` and the `{`.
 */
class ForLoopRecord(val loop: net.exoad.kira.compiler.frontend.parser.ast.statements.WhileIterationStatement, val forAt: SourcePosition, val openAt: SourcePosition, val closeAt: SourcePosition, val head: String)
